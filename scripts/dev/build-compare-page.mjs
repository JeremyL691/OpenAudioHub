#!/usr/bin/env node
// Builds .dev-artifacts/screenshots/index.html: each page at each width and
// colour scheme, with the baseline ("before") capture beside the redesign
// ("after") capture. Paths are relative to that index file.
//
// Usage: node scripts/dev/build-compare-page.mjs

import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../..",
);
const shots = path.join(root, ".dev-artifacts", "screenshots");
const beforeDir = path.join(shots, "before");
const afterDir = path.join(shots, "after");

// The baseline matrix named the overview "dashboard" before T5.1 renamed the route.
const SLUG_MAP = { overview: "dashboard" };
const PAGES = [
    "landing",
    "login",
    "overview",
    "library",
    "recording-detail",
    "settings",
    "docs",
];
const WIDTHS = [375, 768, 1280, 1440];
const SCHEMES = ["light", "dark"];

function listPngs(dir) {
    if (!existsSync(dir)) return new Set();
    return new Set(readdirSync(dir).filter((name) => name.endsWith(".png")));
}

const before = listPngs(beforeDir);
const after = listPngs(afterDir);

function fileFor(set, slug, width, scheme) {
    const name = `${slug}-${width}-${scheme}.png`;
    return set.has(name) ? name : null;
}

function figure(dir, name, caption) {
    if (!name)
        return `<figure class="missing"><figcaption>${caption}: no capture</figcaption></figure>`;
    return `<figure><img loading="lazy" src="${path.posix.join(dir, name)}" alt="${caption}"><figcaption>${caption}</figcaption></figure>`;
}

const sections = [];
for (const page of PAGES) {
    const beforeSlug = SLUG_MAP[page] ?? page;
    const rows = [];
    for (const width of WIDTHS) {
        for (const scheme of SCHEMES) {
            const b = fileFor(before, beforeSlug, width, scheme);
            const a = fileFor(after, page, width, scheme);
            if (!b && !a) continue;
            const label = `${width} px, ${scheme}`;
            rows.push(
                `<div class="pair"><h3>${label}</h3><div class="sides">` +
                    figure("before", b, `Before, ${label}`) +
                    figure("after", a, `After, ${label}`) +
                    `</div></div>`,
            );
        }
    }
    sections.push(`<section><h2>${page}</h2>${rows.join("\n")}</section>`);
}

// Captures that have no baseline counterpart: the new UI states.
const afterOnly = [...after].filter((name) => {
    const slug = name.replace(/-(375|768|1280|1440)-(light|dark)\.png$/, "");
    // `dashboard-*` captures predate the overview rename; the matrix writes `overview-*`.
    return !PAGES.includes(slug) && slug !== "dashboard";
});
const extraCards = afterOnly
    .sort()
    .map(
        (name) =>
            `<figure><img loading="lazy" src="after/${name}" alt="${name}"><figcaption>After: ${name}</figcaption></figure>`,
    )
    .join("\n");
sections.push(
    `<section><h2>After only (new states)</h2><div class="grid">${extraCards}</div></section>`,
);

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Before and after screenshots</title>
<style>
  :root { color-scheme: light dark; }
  body { margin: 0; padding: 16px; font: 14px/1.5 system-ui, sans-serif; background: #f3f4f6; color: #111827; }
  @media (prefers-color-scheme: dark) { body { background: #111827; color: #f9fafb; } }
  h1 { font-size: 20px; margin: 0 0 12px; }
  h2 { font-size: 17px; margin: 24px 0 8px; text-transform: capitalize; }
  h3 { font-size: 13px; font-weight: 600; margin: 12px 0 4px; }
  .sides, .grid { display: grid; gap: 12px; grid-template-columns: repeat(auto-fit, minmax(280px, 1fr)); }
  figure { margin: 0; }
  img { width: 100%; height: auto; border: 1px solid #d1d5db; border-radius: 6px; display: block; }
  figcaption { font-size: 12px; opacity: 0.75; margin-top: 4px; }
  figure.missing { border: 1px dashed #9ca3af; border-radius: 6px; padding: 24px 8px; text-align: center; }
  section { border-top: 1px solid #d1d5db; padding-bottom: 8px; }
</style>
</head>
<body>
<h1>Before and after: OpenAudioHub redesign</h1>
<p>Before is the baseline matrix (SHOT_SET=before). After is the current matrix (SHOT_SET=after). Generated by scripts/dev/build-compare-page.mjs.</p>
${sections.join("\n")}
</body>
</html>
`;

const out = path.join(shots, "index.html");
writeFileSync(out, html, "utf8");
const pairs = sections.length - 1;
console.log(
    `wrote ${path.relative(root, out)}: ${pairs} page sections, ${afterOnly.length} after-only captures`,
);
